"""Export an SB3 SAC actor (net_arch [64, 64], ReLU) to a C header for mlp.c."""

from __future__ import annotations

import re
from pathlib import Path

import numpy as np
from stable_baselines3 import SAC


def _init(a: np.ndarray) -> str:
    if a.ndim == 1:
        return "{" + ", ".join(f"{v:.9e}f" for v in a) + "}"
    return "{" + ",\n".join(_init(row) for row in a) + "}"


def _array(name: str, a: np.ndarray) -> str:
    dims = "".join(f"[{d}]" for d in a.shape)
    return f"static const float {name}{dims} = {_init(a.astype(np.float32))};\n"


def export_header(model: SAC, path: str | Path, env_name: str) -> None:
    lp, mu = model.actor.latent_pi, model.actor.mu
    w = [lp[0].weight, lp[0].bias, lp[2].weight, lp[2].bias, mu.weight, mu.bias]
    w0, b0, w1, b1, w2, b2 = (t.detach().cpu().numpy() for t in w)
    high = float(model.action_space.high[0])
    assert np.allclose(model.action_space.high, high) and np.allclose(model.action_space.low, -high), \
        "mlp.c assumes one symmetric bound for every action"
    names = ["policy_w0", "policy_b0", "policy_w1", "policy_b1", "policy_w2", "policy_b2"]
    body = "".join(_array(n, a) for n, a in zip(names, [w0, b0, w1, b1, w2, b2]))
    Path(path).write_text(
        "/* Generated by export.py from an SB3 SAC actor; do not edit. SPDX-License-Identifier: GPL-3.0-or-later */\n"
        "#pragma once\n"
        f"#define POLICY_ENV \"{env_name}\"\n"
        f"#define POLICY_OBS {w0.shape[1]}\n#define POLICY_HIDDEN {w0.shape[0]}\n#define POLICY_ACT {w2.shape[0]}\n"
        f"#define POLICY_ACTION_SCALE {high:.9e}f\n" + body)


def header_env(path: str | Path) -> str | None:
    """POLICY_ENV of an exported header, or None (missing file, or a header from before POLICY_ENV)."""
    m = re.search(r'^#define POLICY_ENV "([^"]*)"', Path(path).read_text(), re.M) if Path(path).exists() else None
    return m.group(1) if m else None


def reference_action(model: SAC, obs: np.ndarray) -> np.ndarray:
    """Deterministic torch action(s), shape (POLICY_ACT,), float32."""
    return model.predict(np.asarray(obs, dtype=np.float32), deterministic=True)[0].astype(np.float32)
