"""Export an SB3 policy (net_arch [64, 64], ReLU) to a C header for mlp.c.

SAC actor (continuous): the chip returns tanh(mu) * POLICY_ACTION_SCALE per action.
DQN Q-network (discrete): the chip returns argmax Q as one action index (POLICY_DISCRETE).
"""

from __future__ import annotations

import re
from pathlib import Path

import gymnasium as gym
import numpy as np
from stable_baselines3.common.base_class import BaseAlgorithm


def _init(a: np.ndarray) -> str:
    if a.ndim == 1:
        return "{" + ", ".join(f"{v:.9e}f" for v in a) + "}"
    return "{" + ",\n".join(_init(row) for row in a) + "}"


def _array(name: str, a: np.ndarray) -> str:
    dims = "".join(f"[{d}]" for d in a.shape)
    return f"static const float {name}{dims} = {_init(a.astype(np.float32))};\n"


def discrete(model: BaseAlgorithm) -> bool:
    return isinstance(model.action_space, gym.spaces.Discrete)


def policy_n_act(model: BaseAlgorithm) -> int:
    """Floats the chip returns per step: 1 action index (discrete) or one per action dimension."""
    return 1 if discrete(model) else model.action_space.shape[0]


def export_header(model: BaseAlgorithm, path: str | Path, env_name: str) -> None:
    if discrete(model):
        q = model.q_net.q_net  # Linear, ReLU, Linear, ReLU, Linear
        layers, high = (q[0], q[2], q[4]), 1.0
    else:
        layers = (model.actor.latent_pi[0], model.actor.latent_pi[2], model.actor.mu)
        high = float(model.action_space.high[0])
        assert np.allclose(model.action_space.high, high) and np.allclose(model.action_space.low, -high), \
            "mlp.c assumes one symmetric bound for every action"
    w = [t for layer in layers for t in (layer.weight, layer.bias)]
    w0, b0, w1, b1, w2, b2 = (t.detach().cpu().numpy() for t in w)
    names = ["policy_w0", "policy_b0", "policy_w1", "policy_b1", "policy_w2", "policy_b2"]
    body = "".join(_array(n, a) for n, a in zip(names, [w0, b0, w1, b1, w2, b2]))
    Path(path).write_text(
        f"/* Generated by export.py from an SB3 {type(model).__name__} policy; do not edit. "
        "SPDX-License-Identifier: GPL-3.0-or-later */\n"
        "#pragma once\n"
        f"#define POLICY_ENV \"{env_name}\"\n"
        f"#define POLICY_OBS {w0.shape[1]}\n#define POLICY_HIDDEN {w0.shape[0]}\n#define POLICY_OUT {w2.shape[0]}\n"
        f"#define POLICY_DISCRETE {int(discrete(model))}\n#define POLICY_ACT {policy_n_act(model)}\n"
        f"#define POLICY_ACTION_SCALE {high:.9e}f\n" + body)


def header_env(path: str | Path) -> str | None:
    """POLICY_ENV of an exported header, or None (missing file, or a header from before POLICY_ENV)."""
    m = re.search(r'^#define POLICY_ENV "([^"]*)"', Path(path).read_text(), re.M) if Path(path).exists() else None
    return m.group(1) if m else None


def reference_action(model: BaseAlgorithm, obs: np.ndarray) -> np.ndarray:
    """Deterministic torch action(s) as the chip returns them: shape (POLICY_ACT,), float32 (discrete: the index)."""
    a = model.predict(np.asarray(obs, dtype=np.float32), deterministic=True)[0]
    return np.asarray(a, dtype=np.float32).reshape(-1)
